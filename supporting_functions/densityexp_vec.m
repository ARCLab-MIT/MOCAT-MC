function p = densityexp_vec(h)
%
% Uses table from pp. 537 (Table 8-4) in Vallado for simple exponential
% atmospheric density model.
%
% Exponential model, U. S. Standard Atmosphere (1976) and CIRA-72
%
% h is the height above ellipsoid in km.
% density p is returned in kg/m^3. Callers multiply by 1e9 to get kg/km^3
% (see analytic_propagation_vec.m).
%
%if (h >= 150)
%    warning('h is >= 160 km, density calc is broken!')
%end
% these numbers for density units of kg/m^3. The conversion to kg/km^3 is
% done by the callers (they multiply by 1e9), not in this function.

% original by mike shoemaker
% modified by t. kelecy to use "switch" logic rather than "if-then" 12/20/12
% modified 12/26/2012 by t. kelecy to "vectorize" computations
%
% h0   = zeros(size(h));
% p0   = zeros(size(h));
% H   = zeros(size(h));

matrix_h0_p0_H = [0 1.225 7.249;...
                  25 3.899e-2 6.349;...
                  30 1.774e-2 6.682;...
                  40 3.972e-3 7.554;...
                  50 1.057e-3 8.382;...
                  60 3.206e-4 7.714;...
                  70 8.770e-5 6.549;...
                  80 1.905e-5 5.799;...
                  90 3.396e-6 5.382;...
                  100 5.297e-7 5.877;...
                  110 9.661e-8 7.263;...
                  120 2.438e-8 9.473;...
                  130 8.484e-9 12.636;...
                  140 3.845e-9 16.149;...
                  150 2.070e-9 22.523;...
                  180 5.464e-10 29.740;...
                  200 2.789e-10 37.105;...
                  250 7.248e-11 45.546;...
                  300 2.418e-11 53.628;...
                  350 9.518e-12 53.298;...
                  400 3.725e-12 58.515;...
                  450 1.585e-12 60.828;...
                  500 6.967e-13 63.822;...
                  600 1.454e-13 71.835;...
                  700 3.614e-14 88.667;...
                  800 1.170e-14 124.64;...
                  900 5.245e-15 181.05;...
                  1000 3.019e-15 268.00;...
                  Inf 0 0];

% check_h = 1:numel(h);
% for i=2:size(matrix_h0_p0_H,1)
%     im1 = i-1;
%     check_lower = h(check_h)<matrix_h0_p0_H(i,1);
%     check_h_lower = check_h(check_lower);
%     h0(check_h_lower) = matrix_h0_p0_H(im1,1);
%     p0(check_h_lower) = matrix_h0_p0_H(im1,2);
%     H(check_h_lower)  = matrix_h0_p0_H(im1,3);
%     check_h = check_h(~check_lower);
% end

[idx_h] = discretize(h,matrix_h0_p0_H(:,1));
if any(isnan(idx_h))
    error('Input altitude h has element(s) below 0.')
end
h0 = matrix_h0_p0_H(idx_h,1);
p0 = matrix_h0_p0_H(idx_h,2);
H = matrix_h0_p0_H(idx_h,3);

p = p0 .* exp((h0-h)./H);

% Density here is in kg/m^3. The kg/m^3 -> kg/km^3 conversion below MUST
% stay commented out: callers apply the (1000)^3 / 1e9 factor themselves
% (see analytic_propagation_vec.m).
% convert density to kg/km^3
% p = p%* 1000^3
